void Pattern(int iNo)
{
    int iCnt = 0;

    for(iCnt = 1;iCnt <= iNo ;iCnt++)
    {
        printf("%d\t*\t",iCnt);
        
    }
        

}

int main()
{
    int iValue = 0;

    printf("Enter Number :");
    scanf("%d",&iValue);


    Pattern(iValue);

    return EXIT_SUCCESS;
}

